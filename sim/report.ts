// Renders a FullReport as Markdown. Output has no timestamps, so reruns are byte-identical.

import { DEFAULT_CONFIG } from "./config.ts";
import { canonicalJson, metric, SENSITIVITY_METRICS, sha256, type CellResult, type Dist, type FullReport, type Metric } from "./experiments.ts";

const int = new Intl.NumberFormat("en-US", { maximumFractionDigits: 0 });

function fmt(m: Metric, x: number): string {
  if (!Number.isFinite(x)) return "∞";
  switch (m.kind) {
    case "ratio":
      return x.toFixed(3);
    case "percent":
      return `${(x * 100).toFixed(1)}%`;
    case "count":
      return Number.isInteger(x) ? String(x) : x.toFixed(1);
    default:
      return int.format(x);
  }
}

function cell(m: Metric, d: Dist | undefined): string {
  if (!d) return "–";
  return d.p10 === d.p90 ? fmt(m, d.p50) : `${fmt(m, d.p50)} (${fmt(m, d.p10)}–${fmt(m, d.p90)})`;
}

function table(cells: readonly CellResult[], keys: readonly string[], first = "Scenario"): string {
  const header = `| ${first} | ${keys.map((k) => metric(k).label).join(" | ")} |`;
  const sep = `|---|${keys.map(() => "---:").join("|")}|`;
  const rows = cells.map((c) => `| ${c.label} | ${keys.map((k) => cell(metric(k), c.metrics[k])).join(" | ")} |`);
  return [header, sep, ...rows].join("\n");
}

function transposed(cells: readonly CellResult[], keys: readonly string[]): string {
  const header = `| Metric | ${cells.map((c) => c.label).join(" | ")} |`;
  const sep = `|---|${cells.map(() => "---:").join("|")}|`;
  const rows = keys.map((k) => `| ${metric(k).label} | ${cells.map((c) => cell(metric(k), c.metrics[k])).join(" | ")} |`);
  return [header, sep, ...rows].join("\n");
}

export function renderReport(r: FullReport): string {
  const resultsHash = sha256(canonicalJson(r));
  const configHash = sha256(canonicalJson(DEFAULT_CONFIG));
  const all = [...r.matrix, ...r.sensitivity];
  const totals = all.reduce(
    (acc, c) => ({
      runs: acc.runs + c.runs,
      tx: acc.tx + c.conservation.transactions,
      postings: acc.postings + c.conservation.postings,
      checks: acc.checks + c.conservation.invariantChecks,
      identity: acc.identity + c.conservation.identityHeldRuns,
    }),
    { runs: 0, tx: 0, postings: 0, checks: 0, identity: 0 },
  );
  const byHorizon = (days: number) => r.matrix.filter((c) => c.days === days);

  return `# Koinon economy simulation — generated report

> Generated by \`npm run sim:report\`. **Do not edit by hand.** Every behavioural input is an
> assumption (see docs/SIMULATION.md §2), not measured player behaviour.

- Base seed: \`${r.baseSeed}\` · seeds per scenario: **${r.seedsPerCell}** · players: 8
- Default config sha256: \`${configHash}\`
- Results sha256: \`${resultsHash}\` (re-run and compare to check reproducibility)
- Cells show **median across seeds (p10–p90)**. End-of-horizon values unless noted.

## 1. Conservation evidence

| Runs | Transactions validated | Postings validated | Invariant checks | Runs where minted − burned = supply = Σ wallets + escrow | Violations |
|---:|---:|---:|---:|---:|---:|
| ${int.format(totals.runs)} | ${int.format(totals.tx)} | ${int.format(totals.postings)} | ${int.format(totals.checks)} | ${int.format(totals.identity)} / ${int.format(totals.runs)} | 0 |

Every transaction passes \`validateTransaction\` (I1 balanced, I4 bounds, I10 integers, mint/burn
direction) or the run aborts. I2/I3/I6 are checked at the end of every simulated day. I5 (each cached
balance equals the sum of its postings) is recomputed from the full log at the end of each run.
A run that violated anything would have thrown, so the report could not have been generated.

## 2. Engagement × horizon

### Wealth and distribution
${table(r.matrix, ["supply", "medianWallet", "maxWallet", "gini", "nearZeroShare", "nearZeroAtEnd"])}

### Sources, sinks and rewards
${table(r.matrix, ["srcCheckin", "srcDigest", "srcSeason", "sinkPurchase", "sinkRake", "dailyMintPerActiveDay", "seasonCoinsPerParticipant", "mintedPerPlayer"])}

### Wagering and seasons
${table(r.matrix, ["betsMatched", "wagerVolume", "acceptRate", "expiredRate", "transferVolume", "seasonsHeld", "seasonsSkipped"])}

### 10,000 milestone
${table(byHorizon(180), ["walletMilestone", "lifetimeMilestone", "projectedDays"])}

## 3. Sensitivity (medium engagement, ${r.sensitivityDays} days, one change at a time)

${table(r.sensitivity, SENSITIVITY_METRICS, "Variant")}

## 4. Medium engagement, all metrics

${transposed(r.matrix.filter((c) => c.engagement === "medium"), ["supply", "medianWallet", "maxWallet", "gini", "nearZeroShare", "nearZeroAtEnd", "walletMilestone", "lifetimeMilestone", "projectedDays", "dailyMintPerActiveDay", "seasonCoinsPerParticipant", "mintedPerPlayer", "srcGenesis", "srcCheckin", "srcDigest", "srcSeason", "wagerVolume", "betsMatched", "acceptRate", "expiredRate", "blockedByCap", "transferVolume", "seasonsHeld", "seasonsSkipped"])}
`;
}
